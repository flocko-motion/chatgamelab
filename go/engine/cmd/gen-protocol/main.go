// Command gen-protocol writes the TypeScript view of the engine's wire protocol
// beyond OpenAPI, from the Go types that define it.
//
// The playback-engine calls every route through the generated OpenAPI client,
// which types the requests and responses. OpenAPI cannot describe frames on a
// WebSocket, nor the JSON inside an event's value, so this keeps the Go and
// TypeScript sides of those from drifting: the live frames, the payloads only
// events carry, and the problems a refusal names.
//
//	go run ./cmd/gen-protocol            # write web/src/protocol.ts
//	go run ./cmd/gen-protocol -check     # fail if it is stale
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"reflect"
	"sort"
	"strings"

	"engine"
	"engine/api"
)

const output = "web/src/protocol.ts"

func main() {
	check := flag.Bool("check", false, "fail if the generated file is out of date")
	flag.Parse()

	want := generate()

	if !*check {
		if err := os.WriteFile(output, want, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		fmt.Println("wrote", output)
		return
	}

	got, err := os.ReadFile(output)
	if err != nil || !bytes.Equal(got, want) {
		fmt.Fprintf(os.Stderr, "%s is out of date; run: go run ./cmd/gen-protocol\n", output)
		os.Exit(1)
	}
}

func generate() []byte {
	var b strings.Builder
	b.WriteString("// Generated by cmd/gen-protocol. Do not edit.\n")
	b.WriteString("//\n")
	b.WriteString("// The engine's wire protocol, from the Go types that define it.\n\n")

	b.WriteString("/**\n")
	b.WriteString(" * Stream names are not an open vocabulary: each one is an output block a\n")
	b.WriteString(" * genre wired, so this union is the client-side mirror of the graph.\n")
	b.WriteString(" */\n")
	b.WriteString("export type StreamName =\n")
	for _, name := range engine.StreamNames() {
		fmt.Fprintf(&b, "  | %q\n", name)
	}
	b.WriteString("  ;\n\n")

	b.WriteString("/** One item on the session's events, a text frame on the live WebSocket. */\n")
	b.WriteString("export interface SessionEvent {\n")
	for _, field := range tsFields(reflect.TypeOf(engine.SessionEvent{})) {
		fmt.Fprintf(&b, "  readonly %s: %s;\n", field.name, field.tsType)
	}
	b.WriteString("}\n\n")

	b.WriteString("/**\n")
	b.WriteString(" * A `text` event with this value drops the utterance still open, as when a\n")
	b.WriteString(" * broken reply is made again. An empty value closes an utterance.\n")
	b.WriteString(" */\n")
	fmt.Fprintf(&b, "export const TEXT_DISCARD = \"\\u%04x\";\n\n", []rune(engine.TextDiscard)[0])

	b.WriteString("/**\n")
	b.WriteString(" * A binary audio frame of this many bytes drops the speech still playing and\n")
	b.WriteString(" * queued, as when a broken reply is made again. Every other frame is 24 kHz\n")
	b.WriteString(" * mono PCM16.\n")
	b.WriteString(" */\n")
	fmt.Fprintf(&b, "export const AUDIO_DISCARD_BYTES = %d;\n\n", len(engine.AudioDiscard))

	b.WriteString("/**\n")
	b.WriteString(" * A block reporting on itself, carried as JSON in a `state` event's value.\n")
	b.WriteString(" * A block in the turn loop is never finished; `failed` means the game cannot\n")
	b.WriteString(" * continue, and a `problem` event says why.\n")
	b.WriteString(" */\n")
	b.WriteString("export type Phase = \"ready\" | \"working\" | \"failed\";\n\n")
	b.WriteString("export interface BlockState {\n")
	for _, field := range tsFields(reflect.TypeOf(engine.BlockState{})) {
		ts := field.tsType
		if field.name == "phase" {
			ts = "Phase"
		}
		fmt.Fprintf(&b, "  readonly %s: %s;\n", field.name, ts)
	}
	b.WriteString("}\n\n")

	b.WriteString("/** Why a session cannot start or go on. */\n")
	b.WriteString("export type Problem =\n")
	for _, problem := range engine.Problems() {
		fmt.Fprintf(&b, "  | %q\n", problem)
	}
	b.WriteString("  ;\n\n")
	b.WriteString("/** Every problem; an error code outside it is a failure. */\n")
	b.WriteString("export const PROBLEMS: readonly Problem[] = [\n")
	for _, problem := range engine.Problems() {
		fmt.Fprintf(&b, "  %q,\n", problem)
	}
	b.WriteString("];\n\n")
	b.WriteString("/** An error the game goes on after: an `error` event's value. */\n")
	b.WriteString("export type ErrorCode =\n")
	for _, code := range engine.ErrorCodes() {
		fmt.Fprintf(&b, "  | %q\n", code)
	}
	b.WriteString("  ;\n\n")
	b.WriteString("/** Every error code; any other `error` value is a message for whoever debugs. */\n")
	b.WriteString("export const ERROR_CODES: readonly ErrorCode[] = [\n")
	for _, code := range engine.ErrorCodes() {
		fmt.Fprintf(&b, "  %q,\n", code)
	}
	b.WriteString("];\n\n")
	b.WriteString("/** The status values a genre tracks: a `props` event's value, as JSON. */\n")
	b.WriteString("export type Props = Record<string, string>;\n\n")

	b.WriteString("/**\n")
	b.WriteString(" * A refusal: a `problem` event's value. A route's refusal is its error\n")
	b.WriteString(" * response, whose code is the problem.\n")
	b.WriteString(" */\n")
	writeInterface(&b, "Refusal", reflect.TypeOf(engine.Refusal{}))
	b.WriteString("/** A text frame the playback-engine sends on the live WebSocket: typed input. */\n")
	writeInterface(&b, "LiveInput", reflect.TypeOf(api.LiveInput{}))

	b.WriteString("export function isSessionEvent(value: unknown): value is SessionEvent {\n")
	b.WriteString("  if (typeof value !== \"object\" || value === null) return false;\n")
	b.WriteString("  const candidate = value as Partial<SessionEvent>;\n")
	b.WriteString("  return (\n")
	fields := tsFields(reflect.TypeOf(engine.SessionEvent{}))
	for i, field := range fields {
		sep := " &&"
		if i == len(fields)-1 {
			sep = ""
		}
		fmt.Fprintf(&b, "    typeof candidate.%s === %q%s\n", field.name, jsTypeof(field.tsType), sep)
	}
	b.WriteString("  );\n")
	b.WriteString("}\n")

	return []byte(b.String())
}

func writeInterface(b *strings.Builder, name string, t reflect.Type) {
	fmt.Fprintf(b, "export interface %s {\n", name)
	for _, field := range tsFields(t) {
		fmt.Fprintf(b, "  readonly %s: %s;\n", field.name, field.tsType)
	}
	b.WriteString("}\n\n")
}

type tsField struct {
	name   string
	tsType string
}

func tsFields(t reflect.Type) []tsField {
	var out []tsField
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if !f.IsExported() {
			continue
		}
		// An embedded struct's fields are its parent's in JSON.
		if f.Anonymous && f.Type.Kind() == reflect.Struct {
			out = append(out, tsFields(f.Type)...)
			continue
		}
		name := f.Name
		if tag := f.Tag.Get("json"); tag != "" {
			if parts := strings.Split(tag, ","); parts[0] != "" && parts[0] != "-" {
				name = parts[0]
			}
		}
		ts := tsType(f.Type)
		if f.Type == reflect.TypeOf(engine.Problem("")) {
			ts = "Problem"
		}
		// The stream is the one field whose values are closed, so it carries
		// the union rather than a bare string.
		if name == "Stream" {
			ts = "StreamName"
		}
		// A JSON name that is no identifier, such as audio-out, is quoted.
		if strings.ContainsAny(name, "-") {
			name = fmt.Sprintf("%q", name)
		}
		// Optional in Go's JSON sense means optional in TypeScript's.
		if strings.Contains(f.Tag.Get("json"), ",omitempty") {
			name += "?"
		}
		out = append(out, tsField{name: name, tsType: ts})
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].name < out[j].name })
	return out
}

func tsType(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Slice:
		return tsType(t.Elem()) + "[]"
	case reflect.Pointer:
		return tsType(t.Elem())
	case reflect.Map:
		return "Record<string, " + tsType(t.Elem()) + ">"
	case reflect.Struct:
		return t.Name()
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	default:
		return "unknown"
	}
}

func jsTypeof(ts string) string {
	switch ts {
	case "boolean", "number":
		return ts
	default:
		// Including StreamName: a union of string literals is a string at
		// runtime, which is all a guard can check.
		return "string"
	}
}
